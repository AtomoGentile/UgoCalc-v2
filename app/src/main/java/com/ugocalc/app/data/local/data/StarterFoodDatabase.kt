    /**
     * Restituisce la categoria italiana CREA per [name]: controlla prima la corrispondenza esatta
     * (case-insensitive e senza diacritici) nel catalogo [CATEGORY_ENTRIES], poi usa un fallback
     * per parole chiave utile anche per le voci importate o inserite manualmente dall'utente.
     */
    fun categoryForFoodName(name: String): ItalianFoodCategory? {
        val normalized = normalizeCategoryKey(name)
        if (normalized.isEmpty()) return null
        EXACT_CATEGORY_BY_NORMALIZED_NAME[normalized]?.let { return it }
        for (rule in FALLBACK_CATEGORY_RULES) {
            if (rule.keywords.any { normalized.contains(it) }) {
                return rule.category
            }
        }
        return null
    }

    private fun normalizeCategoryKey(raw: String): String {
        val decomposed = Normalizer.normalize(raw.trim().lowercase(Locale.ROOT), Normalizer.Form.NFD)
        return decomposed
            .replace(Regex("\\p{InCombiningDiacriticalMarks}+"), "")
            .replace(Regex("\\s+"), " ")
    }
